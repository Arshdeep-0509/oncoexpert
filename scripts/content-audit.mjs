// Content audit: for each page, every text block with its SOURCE tag (the nearest "// SOURCE:"
// comment above it), then every NEW line and every PENDING DOCTOR item.
// Usage: npm run audit:content
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const PAGES = {
  "Book Appointment": ["content/pages/book-appointment.ts", "content/pages/book-appointment.seo.ts"],
  "About Us": ["content/pages/about-us.ts", "content/pages/about-us.seo.ts"],
  Colorectal: ["content/pages/colorectal-cancer.ts", "content/pages/colorectal-cancer.seo.ts"],
  Endometrial: ["content/pages/endometrial-cancer.ts", "content/pages/endometrial-cancer.seo.ts"],
  Lung: ["content/pages/lung-cancer.ts", "content/pages/lung-cancer.seo.ts"],
  Ovarian: ["content/pages/ovarian-cancer.ts", "content/pages/ovarian-cancer.seo.ts"],
  Thyroid: ["content/pages/thyroid-cancer.ts", "content/pages/thyroid-cancer.seo.ts"],
  "Shared (every page)": [
    "content/shared/sections.ts",
    "content/shared/organization.ts",
    "content/shared/approvals.ts",
    "content/site.ts",
    "app/robots.ts",
    "lib/llms.ts",
  ],
};

const clean = (s) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

function audit(file) {
  const src = fs.readFileSync(path.join(root, file), "utf8").split(/\r?\n/);
  const blocks = [];
  const pending = [];
  // The header comment applies to the whole file (.seo.ts files: "SOURCE: NEW (every sentence here)").
  let tag = /SOURCE:\s*NEW \(every sentence here\)/.test(src.slice(0, 15).join("\n")) ? "NEW" : "—";
  for (let i = 0; i < src.length; i++) {
    const line = src[i];
    const t = line.match(/\/\/\s*SOURCE:\s*(.+)$/);
    if (t) tag = t[1].trim();
    const p = line.match(/(?:\/\/|\*)\s*PENDING DOCTOR:?\s*(.*)$/);
    if (p) {
      let text = p[1];
      for (let j = i + 1; j < src.length && /^\s*\/\/\s{1,3}\S/.test(src[j]) && !/SOURCE:|PENDING/.test(src[j]); j++)
        text += " " + src[j].replace(/^\s*\/\/\s*/, "");
      // The file header's legend ("PENDING DOCTOR → something only the doctor can confirm") is not an item.
      if (!text.trim().startsWith("→")) pending.push(clean(text));
    }
    if (/^\s*(\/\/|\*|import)/.test(line)) continue;
    for (const m of line.matchAll(/(?:^|[\s,[{(])(?:(\w+):\s*)?(["`])((?:(?!\2)[^\\]|\\.){12,}?)\2/g)) {
      const value = m[3];
      if (/^(https?:|\/|#|@\/)|\.(jpg|png|webp|svg)$|^[a-z-]+$/.test(value)) continue;
      blocks.push({ key: m[1] ?? "", tag: tag.length > 70 ? tag.slice(0, 67) + "…" : tag, text: clean(value) });
    }
  }
  return { blocks, pending };
}

const out = [
  "# Content audit",
  "",
  "Generated by `npm run audit:content`. For each page: every text",
  "block with the SOURCE tag above it (EXISTING: copied from the live site, render exactly; NEW: added",
  "by us, pending the doctor's approval; DOCTOR: written by Dr. Sunil), then the NEW lines, then every",
  "PENDING DOCTOR item. `${…}` marks a figure filled in from the content (never retyped).",
  "",
];
for (const [page, files] of Object.entries(PAGES)) {
  out.push(`## ${page}`, "");
  const all = files.map((f) => ({ f, ...audit(f) }));
  out.push("### Every text block", "", "| File | Key | SOURCE | Text |", "| --- | --- | --- | --- |");
  for (const { f, blocks } of all)
    for (const b of blocks)
      out.push(
        `| ${path.basename(f)} | ${b.key} | ${b.tag} | ${b.text.slice(0, 160)}${b.text.length > 160 ? "…" : ""} |`,
      );
  out.push("", "### NEW lines", "");
  const news = all.flatMap(({ blocks }) => blocks.filter((b) => /^NEW/.test(b.tag)));
  out.push(...(news.length ? news.map((b) => `- ${b.text}`) : ["- (none)"]), "");
  out.push("### PENDING DOCTOR", "");
  const pend = all.flatMap(({ f, pending }) => pending.map((p) => `- (${path.basename(f)}) ${p}`));
  out.push(...(pend.length ? pend : ["- (none)"]), "");
}
process.stdout.write(out.join("\n"));
