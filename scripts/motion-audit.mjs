// Motion audit: one table per page, generated from the page CSS (components/pages/<page>/*.css) and
// the shared CSS each page uses. For every `animation:` declaration: the element (selector), what
// starts it, its duration, whether it loops, what pauses or stops it, and the reduced-motion
// fallback. Usage: npm run audit:motion
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const PAGES = {
  "Book Appointment": { dirs: [], shared: ["components/shared/appointment"] },
  "About Us": { dirs: ["components/pages/about-us"], shared: ["components/shared/doctor-ring"] },
  Colorectal: { dirs: ["components/pages/colorectal-cancer"], shared: [] },
  Endometrial: { dirs: ["components/pages/endometrial-cancer"], shared: [] },
  Lung: {
    dirs: ["components/pages/lung-cancer"],
    shared: ["components/shared/technique-compare", "components/shared/survival-chart.css"],
  },
  Ovarian: {
    dirs: ["components/pages/ovarian-cancer"],
    shared: [
      "components/shared/symptom-grid",
      "components/shared/package-cards",
      "components/shared/survival-chart.css",
    ],
  },
  Thyroid: {
    dirs: ["components/pages/thyroid-cancer"],
    shared: [
      "components/shared/symptom-grid",
      "components/shared/package-cards",
      "components/shared/survival-chart.css",
    ],
  },
};

const cssFiles = (p) => {
  const abs = path.join(root, p);
  if (!fs.existsSync(abs)) return [];
  if (abs.endsWith(".css")) return [abs];
  return fs
    .readdirSync(abs)
    .filter((f) => f.endsWith(".css"))
    .map((f) => path.join(abs, f));
};

/** Every rule with an `animation:` in a file, with its selector and whether it sits in a no-preference block. */
function rules(file) {
  const css = fs.readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const out = [];
  const stack = [];
  let buf = "";
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (c === "{") {
      stack.push(buf.trim());
      buf = "";
    } else if (c === "}") {
      const sel = stack.pop() ?? "";
      const body = buf;
      const m = body.match(/animation:\s*([^;]+);/);
      if (m && !sel.startsWith("@keyframes") && !/^(from|to|\d+%)/.test(sel)) {
        out.push({
          sel: sel.replace(/\s+/g, " "),
          anim: m[1].trim(),
          motionOnly: stack.some((s) => s.includes("no-preference")),
        });
      }
      buf = "";
    } else buf += c;
  }
  return out;
}

const pauseRules = (file) => fs.readFileSync(file, "utf8");

function describe(r, css) {
  const s = r.sel;
  const loop = /infinite/.test(r.anim) ? "yes" : /\b\d+\s*;?$/.test(r.anim) || / \d+ /.test(r.anim) ? "repeats" : "no";
  const dur = (r.anim.match(/(\d*\.?\d+m?s|var\(--[a-z-]+(?:,\s*[\d.]+m?s)?\))/) ?? [""])[0];
  const trigger = /data-inview/.test(s)
    ? "scrolled into view"
    : /data-state|data-filter|data-step|aria-|data-open|\[open\]|data-selected|data-active/.test(s)
      ? "an interaction (state change)"
      : /hover|focus/.test(s)
        ? "hover / focus"
        : "page load (after the intro)";
  const name = (r.anim.match(/^([a-z][\w-]*)/) ?? [""])[0];
  const stops = [];
  const esc = s
    .split(" ")
    .pop()
    .replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  if (loop === "yes") {
    if (new RegExp(`data-paused[^{]*${esc}`).test(css) || /\[data-paused\]/.test(css))
      stops.push("pause button (48px)");
    if (/:hover|:focus-within/.test(css)) stops.push("hover / focus");
    if (/data-offscreen/.test(css)) stops.push("off-screen");
  }
  return {
    element: `\`${s.length > 70 ? s.slice(0, 67) + "…" : s}\``,
    name,
    trigger,
    dur,
    loop,
    stop: loop === "yes" ? stops.join(", ") || "**none**" : "n/a (runs once)",
    reduced: r.motionOnly ? "final state (no animation)" : "**animates**",
  };
}

const lines = [
  "# Motion audit",
  "",
  "Generated by `npm run audit:motion` from the page CSS. Every animation sits",
  "inside `@media (prefers-reduced-motion: no-preference)`; the default CSS is the final state, so",
  "reduced motion shows everything at rest. Only transform, opacity and SVG stroke draws are animated.",
  "Loops over 5s pause on hover / focus or with the hero's 48px pause button, and stop off-screen.",
  "Interaction transitions (switches, filters, tabs, cards) are CSS transitions on the same",
  "properties and are not listed.",
  "",
];
for (const [page, { dirs, shared }] of Object.entries(PAGES)) {
  lines.push(`## ${page}`, "");
  lines.push("| Element | Animation | Trigger | Duration | Loop | Pause / stop | Reduced motion |");
  lines.push("| --- | --- | --- | --- | --- | --- | --- |");
  let n = 0;
  for (const file of [...dirs, ...shared].flatMap(cssFiles)) {
    const css = pauseRules(file);
    for (const r of rules(file)) {
      const d = describe(r, css);
      lines.push(
        `| ${d.element} | ${d.name} (${path.basename(file)}) | ${d.trigger} | ${d.dur} | ${d.loop} | ${d.stop} | ${d.reduced} |`,
      );
      n++;
    }
  }
  if (!n) lines.push("| (none: the page has no animations of its own; the form fades in with Reveal) | | | | | | |");
  lines.push("");
}
process.stdout.write(lines.join("\n"));
